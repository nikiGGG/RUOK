/**
 * Canonical, dialect-independent backup/restore types (FR-008 / US4 / WP06).
 *
 * This module is the single source of truth for:
 *  - the version-2 JSON wire format (`BackupDocumentV2`), which must stay
 *    readable/round-trippable for any supported source/target pair;
 *  - the adapter's *consistent snapshot* (`BackupSnapshot`), which every
 *    adapter builds from its own dialect tables inside a single transaction;
 *  - the validated, fully-resolved *restore command plan* (`RestoreCommandPlan`),
 *    which each adapter executes atomically.
 *
 * All IDs in the command plan are freshly generated by the canonical planner
 * and every reference (tag name, saved-query name, objective parent index,
 * widget config query reference) is resolved to a concrete id BEFORE any row
 * is mutated. Adapters never validate, remap or generate ids.
 *
 * Version 2 is the only supported version. Optional compatible additions
 * (e.g. the `scoreLabel` key-result field) are read and written by v2 without
 * bumping the version; a future version that changes the format would be a
 * new-version necessity and is intentionally out of scope here.
 */
