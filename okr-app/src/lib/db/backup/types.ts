/** The only version understood by export and restore. */
export const BACKUP_VERSION = 2 as const;

// ---------------------------------------------------------------------------
// Version-2 wire document (the JSON that leaves / enters the API)
// ---------------------------------------------------------------------------

export interface BackupPreferences {
	timezone: string;
	weekStartDay: WeekStartDay;
	bgColor: string | null;
}

export interface ValueExport {
	title: string;
	rank: number;
	description: string | null;
	createdAt: string;
	updatedAt: string;
	principles: PrincipleExport[];
}

export interface PrincipleExport {
	title: string;
	description: string | null;
	examples: string | null;
	createdAt: string;
	updatedAt: string;
}

export interface TagExport {
	name: string;
	color: string | null;
	category: string | null;
}

export interface SavedQueryExport {
	name: string;
	description: string | null;
	queryType: 'progress' | 'widget' | 'general';
	code: string;
	createdAt: string;
	updatedAt: string;
}

export interface KeyResultExport {
	title: string;
	details: string | null;
	weight: number;
	score: number;
	scoreLabel: string | null;
	expectedHours: number | null;
	sortOrder: number;
	measurementType: 'slider' | 'checkboxes' | 'custom_query';
	checkboxItems: string | null;
	progressQueryName: string | null;
	progressQueryCode: string | null;
	widgetQueryName: string | null;
	widgetQueryCode: string | null;
	createdAt: string;
	updatedAt: string;
}

export interface ObjectiveExport {
	title: string;
	description: string | null;
	level: 'yearly' | 'monthly';
	year: number;
	month: number | null;
	weight: number;
	category: string | null;
	colorIndex: number | null;
	parentIndex: number | null;
	createdAt: string;
	updatedAt: string;
	keyResults: KeyResultExport[];
}

export interface TaskAttributeExport {
	key: string;
	value: string;
	valueType: 'number' | 'time' | 'text' | 'boolean';
}

export interface TaskExport {
	title: string;
	completed: boolean;
	completedAt: string | null;
	sortOrder: number;
	timeSpentMs: number;
	timerStartedAt: string | null;
	createdAt: string;
	updatedAt: string;
	attributes: TaskAttributeExport[];
	tagNames: string[];
}

export interface DailyMetricsExport {
	previousNightBedTime: string | null;
	wakeUpTime: string | null;
	sleepLength: string | null;
	cardioLoad: number | null;
	fitbitReadiness: number | null;
	steps: number | null;
	heartPoints: number | null;
	restingHeartRate: number | null;
	customMetrics: string | null;
}

export interface TimeCommitmentExport {
	numberOfWeeks: number;
	availableHoursPerWeekday: number;
	availableHoursPerWeekend: number;
}

export interface TimePeriodExport {
	periodType: 'yearly' | 'monthly' | 'weekly' | 'daily';
	year: number;
	month: number | null;
	week: number | null;
	day: string | null;
	notes: string | null;
	reviewWhatWorked: string | null;
	reviewImprovements: string | null;
	createdAt: string;
	updatedAt: string;
	timeCommitment: TimeCommitmentExport | null;
	dailyMetrics: DailyMetricsExport | null;
	tasks: TaskExport[];
}

export interface WidgetExport {
	title: string;
	widgetType: 'builtin' | 'custom' | 'saved';
	config: string;
	sortOrder: number;
	page: string;
	createdAt: string;
}

export interface MetricsTemplateExport {
	name: string;
	effectiveFrom: string;
	metricsDefinition: string;
	createdAt: string;
	updatedAt: string;
}

export interface DailyMetricValueExport {
	date: string;
	metricName: string;
	value: string | null;
	source: string;
}

export interface ReflectionExport {
	level: 'yearly' | 'monthly';
	year: number;
	month: number | null;
	reflection: string;
	createdAt: string;
	updatedAt: string;
}

export interface BackupData {
	values: ValueExport[];
	orphanPrinciples: PrincipleExport[];
	tags: TagExport[];
	savedQueries: SavedQueryExport[];
	objectives: ObjectiveExport[];
	timePeriods: TimePeriodExport[];
	dashboardWidgets: WidgetExport[];
	metricsTemplates: MetricsTemplateExport[];
	dailyMetricValues: DailyMetricValueExport[];
	objectiveReflections: ReflectionExport[];
}

export interface BackupDocumentV2 {
	version: typeof BACKUP_VERSION;
	exportedAt: string;
	preferences: BackupPreferences;
	data: BackupData;
}

// ---------------------------------------------------------------------------
// Consistent snapshot produced by each adapter (inside one transaction)
// ---------------------------------------------------------------------------

export interface BackupSnapshot {
	user: UserRow;
	values: ValueRow[];
	principles: PrincipleRow[];
	tags: TagRow[];
	savedQueries: SavedQueryRow[];
	objectives: ObjectiveRow[];
	keyResults: KeyResultRow[];
	timePeriods: TimePeriodRow[];
	timeCommitments: TimeCommitmentRow[];
	tasks: TaskRow[];
	taskAttributes: TaskAttributeRow[];
	taskTags: TaskTagRow[];
	dailyMetrics: DailyMetricsRow[];
	dashboardWidgets: DashboardWidgetRow[];
	metricsTemplates: MetricsTemplateRow[];
	dailyMetricValues: DailyMetricValueRow[];
	objectiveReflections: ObjectiveReflectionRow[];
}

// ---------------------------------------------------------------------------
// Restore command plan (validated, fully resolved, ids freshly generated)
// ---------------------------------------------------------------------------

/** A value together with the principles nested under its (new) value id. */
export interface ValueRestoreEntry {
	value: NewValueRow;
	principles: NewPrincipleRow[];
}

/** An objective together with its key results (references already resolved). */
export interface ObjectiveRestoreEntry {
	objective: NewObjectiveRow;
	keyResults: NewKeyResultRow[];
}

/** A period together with its optional commitment, metrics and tasks. */
export interface TimePeriodRestoreEntry {
	period: NewTimePeriodRow;
	commitment: NewTimeCommitmentRow | null;
	dailyMetrics: NewDailyMetricsRow | null;
	tasks: TaskRestoreEntry[];
}

/** A task together with its attributes and resolved tag ids. */
export interface TaskRestoreEntry {
	task: NewTaskRow;
	attributes: NewTaskAttributeRow[];
	tagIds: string[];
}

export interface RestoreStats {
	tags: number;
	values: number;
	principles: number;
	savedQueries: number;
	objectives: number;
	keyResults: number;
	timePeriods: number;
	tasks: number;
	taskAttributes: number;
	taskTags: number;
	dailyMetrics: number;
	timeCommitments: number;
	dashboardWidgets: number;
	metricsTemplates: number;
	dailyMetricValues: number;
	objectiveReflections: number;
}

/**
 * The complete, backend-independent restore. Every row carries a fresh
 * `crypto.randomUUID()` id and every foreign key / reference is an explicit,
 * resolvable value. The target user's id is pinned in {@link userId}.
 */
export interface RestoreCommandPlan {
	userId: string;
	preferences: BackupPreferences;
	tags: NewTagRow[];
	values: ValueRestoreEntry[];
	orphanPrinciples: NewPrincipleRow[];
	savedQueries: NewSavedQueryRow[];
	objectives: ObjectiveRestoreEntry[];
	timePeriods: TimePeriodRestoreEntry[];
	dashboardWidgets: NewDashboardWidgetRow[];
	metricsTemplates: NewMetricsTemplateRow[];
	dailyMetricValues: NewDailyMetricValueRow[];
	objectiveReflections: NewObjectiveReflectionRow[];
	stats: RestoreStats;
}